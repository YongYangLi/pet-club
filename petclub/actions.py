def get(key):
    """取一条指令（带 key）。没有就返回 None。"""
    item = ACTIONS.get(key)
    if item is None:
        return None
    return dict(item, key=key)


def is_local(key):
    """这条指令是不是只在自己屏幕上生效。"""
    item = ACTIONS.get(key)
    return bool(item) and item.get('scope') == SCOPE_LOCAL


def pick(pool, rng=None):
    """从台词池里挑一句。池子是空的就是「这次不冒泡」，返回空串。"""
    if isinstance(pool, str):
        return pool
    if not pool:
        return ''
    return (rng or random).choice(pool)


def say_line(key, role, scope='s', rng=None):
    """发起时，被指令作用到的那个角色说的话。

    scope='s' 是传出去的指令说的（对方也看得到），
    scope='l' 是不出门的指令说的（只有我这块屏幕看得到）。
    """
    if not role:
        return ''
    return pick(VOICE.get(role, {}).get('%s.%s' % (scope, key), ()), rng)


def reply_line(key, role, rng=None):
    """别人对我下指令时，我的角色回一句。空串 = 只做动作不说话。"""
    if not role:
        return ''
    return pick(VOICE.get(role, {}).get('s.%s.me' % key, ()), rng)


