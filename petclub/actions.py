def get(key):
    """取一条指令（带 key）。没有就返回 None。"""
    item = ACTIONS.get(key)
    if item is None:
        return None
    return dict(item, key=key)


def pick(pool, rng=None):
    """从台词池里挑一句。池子是空的就是「这次不冒泡」，返回空串。"""
    if isinstance(pool, str):
        return pool
    if not pool:
        return ''
    return (rng or random).choice(pool)


def say_line(key, role, rng=None):
    """下这条指令时，我的角色说的那句。"""
    if not role:
        return ''
    return pick(VOICE.get(role, {}).get('s.%s' % key, ()), rng)


def reply_line(key, role, rng=None):
    """别人对我下指令时，我的角色回一句。空串 = 只做动作不说话。"""
    if not role:
        return ''
    return pick(VOICE.get(role, {}).get('s.%s.me' % key, ()), rng)


