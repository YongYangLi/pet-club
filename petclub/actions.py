# ---------------- 互动的「系统提示」 ----------------
#
# 传出去的互动不只是让对方动一下，它还得在聊天记录里留下一条痕迹 ——
# 否则一句话飘完就没了，过一会儿谁也想不起「刚才他敲我干什么」。
#
# 这条痕迹不是消息，是**系统提示**：和我自己打的字长得不一样，
# 居中的灰字（微信里「张三 拍了拍你」就是那个样式）。
#
# 四种视角，所以每条指令四句话：
#   to_one    我发起，只对某个人        → 你 跟{who}打了个招呼
#   to_all    我发起，对全员            → 你 向大家打了个招呼
#   from_one  别人发起，只对我          → 胡大神 跟你打了个招呼
#   from_all  别人发起，对全员          → 胡大神 向大家打了个招呼

