def tip_text(kind, actor, one=False, target=None):
    """一条互动提示的文案。不认识的指令返回空串（不记）。"""
    pat = TIP.get(kind)
    if pat is None:
        return ''
    actor = actor or ''
    if actor == '你':
        return '你 ' + (pat['to_one'].format(who=target or '') if one
                       else pat['to_all'])
    return '%s %s' % (actor, pat['from_one'] if one else pat['from_all'])


